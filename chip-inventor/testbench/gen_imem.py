"""Regenerate the FIRMWARE-selectable imem and sync it into every design copy.

  python chip-inventor/testbench/gen_imem.py

Writes rtl/imem.v, then replaces module imem in hdl.v (the canvas top,
pasted into ChipInventor) and rtl/top.v. The Stage 2 ROM (FIRMWARE 0) is carried
over verbatim from the current rtl/imem.v; test ROMs come from
testbench/firmware.py. Upload rtl/imem.v as the canvas imem block code.

FIRMWARE 4 (the organiser's verbatim GPIO/UART test firmware) and FIRMWARE 5
(our Stage 3 grid-aware EV charger application) are loaded from a
Firmware-Builder firmware.txt, so rerun this script after rebuilding
chip-inventor/firmware/ with `make`. FIRMWARE 6 is the crcb vs software
CRC-16 cycle bench.
"""
from pathlib import Path
import re
import sys

CHIP = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CHIP / 'testbench'))
from firmware import PROGRAMS

ITEM = re.compile(r"^\s*10'd\d+\s*:.*$", re.M)


def stage2_items(imem_text):
    """Case items of the Stage 2 ROM, from either the old or the new imem."""
    marker = imem_text.find('// FIRMWARE 0:')
    body = imem_text[marker:] if marker >= 0 else imem_text
    items = []
    for line in body.splitlines():
        if ITEM.match(line):
            items.append(line.strip())
        elif items and line.strip().startswith('default'):
            break
    assert len(items) > 200, f'Stage 2 ROM looks wrong ({len(items)} items)'
    return items


def rom_items(asm):
    return [f"10'd{(addr - 0x00400000) // 4}: data_o = 32'h{word:08x}; // {text}"
            for addr, word, text, comment in asm.assemble()]


def case_block(title, items, default, indent='                '):
    lines = [f'{indent}// FIRMWARE {title}', f'{indent}case (addr_i[9:0])']
    lines += [f'{indent}    {item}' for item in items]
    lines += [f'{indent}    {default}', f'{indent}endcase']
    return '\n'.join(lines)


def build():
    s2 = stage2_items((CHIP / 'rtl/imem.v').read_text(encoding='utf-8'))
    branches = []
    for n, (title, prog) in sorted(PROGRAMS.items()):
        kw = 'if' if not branches else 'end else if'
        branches.append(f'            {kw} (FIRMWARE == {n}) begin\n'
                        + case_block(f'{n}: {title}', rom_items(prog()),
                                     "default: data_o = 32'h0000006f; // j . (park)"))
    branches.append('            end else begin\n'
                    + case_block('0: official Stage 2 validation firmware', s2,
                                 "default: data_o = 32'h00000013; // NOP (addi x0, x0, 0)")
                    + '\n            end')
    return f'''// Instruction ROM. FIRMWARE selects the program at elaboration time:
//   0 = official Stage 2 validation firmware (default; what synthesis builds)
//   1 = GPIO system test, 2 = UART echo test, 3 = full system test
//   4 = organiser official GPIO/UART firmware (verbatim)
//   5 = grid-aware EV charger application (Stage 3)
// Test programs are simulation-only: a testbench selects one with
//   defparam dut.<imem instance>.FIRMWARE = N;
// FIRMWARE is a constant, so synthesis folds away the unselected ROMs.
// Generated by canvas_blocks/gen_imem.py - edit that, not this file.
module imem #(
    parameter integer FIRMWARE = 0
) (
    input  wire        clk_i,
    input  wire [31:0] addr_i,
    input  wire        oe_i,
    output reg  [31:0] data_o
);
    always @(*) begin
        data_o = 32'h00000000;
        if (oe_i) begin
{chr(10).join(branches)}
        end
    end
endmodule
'''


def main():
    module = build()
    (CHIP / 'rtl/imem.v').write_text(module, encoding='utf-8')
    print('wrote rtl/imem.v')
    body = re.search(r'module imem\b.*?endmodule', module, re.S).group(0)
    for rel in ['hdl.v', 'rtl/top.v']:
        path = CHIP / rel
        if not path.exists():
            continue
        text = path.read_text(encoding='utf-8')
        text, count = re.subn(r'module imem\b.*?endmodule', lambda _: body, text, flags=re.S)
        assert count == 1, rel
        path.write_text(text, encoding='utf-8')
        print('synced', rel)


if __name__ == '__main__':
    main()
