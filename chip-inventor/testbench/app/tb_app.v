`timescale 1ns/1ps
// Model of the organiser's ./emu host plus the AWS FPGA wrapper, driving our
// RTL. Each emu_* task mirrors one ./emu option, so a passing run here is a
// passing ./emu command on the FPGA.
//
// Modelled from RVBL-Emulator/src/emu.c and its README.md (spec SS3):
//   - every command resets the processor, but the GPIO input value persists
//     across that reset (only the direction byte is rewritten) -- PRESET_IN
//   - options run strictly in order; the first mismatch skips the rest
//   - -r reads the first eight bytes transmitted, through a running pointer
//   - -t sends multi-byte values low byte first
//   - log text copies emu.c's own strings
//
// The scenario body is generated by scenarios.py into scenario.vh.
module testbench;

`ifndef IMEM_INST
`define IMEM_INST blk3564_70
`endif
`ifndef FIRMWARE_SEL
`define FIRMWARE_SEL 5
`endif
`ifndef EMU_GAP
`define EMU_GAP 20000          // scaled-down 50 ms AXI delay; >= one record's
`endif                         // TX time (8 bytes x 1740 = 13920 cycles)
`ifndef EMU_T_GAP
`define EMU_T_GAP `EMU_GAP     // gap before each -t (0 for back-to-back)
`endif
`ifndef EMU_BYTE_GAP
`define EMU_BYTE_GAP 2000      // gap between bytes inside one -t
`endif
`ifndef PRESET_IN
`define PRESET_IN 0
`endif

    reg clk = 0;
    always #25 clk = ~clk;                 // 20 MHz, matches config.json

    localparam integer BIT = 174;          // CLKS_PER_BIT at 115200 baud

    reg rst = 1, rx = 1;
    wire [7:0] pins_i, pins_o, pins_oe_o;
    wire tx, halt;
    wire [31:0] pc_dbg, x4_dbg;

    // Emulator-side pin state. dir bit 1 = emulator observes the processor
    // output, 0 = emulator drives a value in (README "GPIO direction").
    reg [7:0] emu_dir = 8'h01;             // fpga_init's default direction
    reg [7:0] emu_in  = `PRESET_IN;        // persists across the reset
    reg dir_written = 0;

    // Pad model: the chip wins when it drives, else the emulator's value (or 0
    // on a line the emulator has released but the chip is not driving).
    genvar g;
    generate
        for (g = 0; g < 8; g = g + 1) begin : pad
            assign pins_i[g] = pins_oe_o[g] ? pins_o[g]
                                            : (emu_dir[g] ? 1'b0 : emu_in[g]);
        end
    endgenerate

    top dut (.clk_i(clk), .rst_i(rst), .halt_o(halt),
             .pins_i(pins_i), .pins_o(pins_o), .pins_oe_o(pins_oe_o),
             .rx_i(rx), .tx_o(tx), .pc_dbg_o(pc_dbg), .x4_dbg_o(x4_dbg));

    defparam dut.`IMEM_INST.FIRMWARE = `FIRMWARE_SEL;
`ifdef WATCHDOG_TIMER_HZ
    // Accelerate only the watchdog divider in focused tests; UART stays 20 MHz.
    defparam dut.meter_timer_inst.CLK_HZ = `WATCHDOG_TIMER_HZ;
    always @(negedge tx) begin
        if (!rst && pins_o[4] !== 1'b0)
            $fatal(1, "contactor must open before fault report transmission");
    end
`endif

    integer errors = 0;
    integer aborted = 0;                   // emu.c: first [error] -> main_end
    integer halted = 0;

    // ---- reply-byte window (emu.c fpga_read_uart) ----------------------
    reg [7:0] rx_buf [0:7];
    integer rx_count = 0;                  // bytes seen on tx_o
    integer rx_ptr = 0;                    // bytes consumed by -r
    integer overflow = 0;

    always @(posedge clk) if (halt) halted <= 1;

    // Background TX monitor: decode every byte the processor sends.
    reg [7:0] mon;
    integer mb;
    initial begin
        forever begin
            @(negedge tx);                 // start bit
            repeat (BIT + BIT / 2) @(posedge clk);
            for (mb = 0; mb < 8; mb = mb + 1) begin
                mon[mb] = tx;              // LSB first
                repeat (BIT) @(posedge clk);
            end
            if (rx_count < 8) begin
                rx_buf[rx_count] = mon;
                rx_count = rx_count + 1;
            end else if (!overflow) begin
                overflow = 1;
                $display("[tb] FAIL more than 8 bytes transmitted (9th = 0x%02X)", mon);
                errors = errors + 1;
            end
        end
    end

    // Contention check: once the emulator has released a line (dir bit 1) the
    // chip may drive it; if the chip drives a line the emulator still drives,
    // both fight.
    always @(posedge clk) begin
        if (dir_written && ((pins_oe_o & ~emu_dir) != 8'h00) && !aborted) begin
            $display("[tb] FAIL contention: oe=%02X dir=%02X", pins_oe_o, emu_dir);
            errors = errors + 1;
            aborted = 1;
        end
    end

    task emu_begin;
        begin
            emu_in = `PRESET_IN;           // IN survives the reset
            repeat (3) @(negedge clk);
            rst = 0;
            repeat (1000) @(negedge clk);
            $display("[ok] RISC-V started!");
        end
    endtask

    task emu_d(input [7:0] value);
        begin
            if (!aborted) begin
                repeat (`EMU_GAP) @(negedge clk);
                emu_dir = value;
                dir_written = 1;
                $display("[ok] Written 0x%08X to DIRECTION", value);
            end
        end
    endtask

    task emu_i(input [7:0] value);
        begin
            if (!aborted) begin
                repeat (`EMU_GAP) @(negedge clk);
                emu_in = value;
                $display("[ok] Written 0x%08X to INPUT PINS", value);
            end
        end
    endtask

    // state == 8'hFF skips the x4 check (used for the organiser firmware,
    // which has no application state).
    task emu_o(input [7:0] exp, input [7:0] state);
        reg [7:0] got;
        begin
            if (!aborted) begin
                repeat (`EMU_GAP) @(negedge clk);
                got = pins_o & pins_oe_o;
                if (got !== exp) begin
                    $display("[error] OUT read error. Expected 0x%08X. Got 0x%08X", exp, got);
                    errors = errors + 1;
                    aborted = 1;
                end else begin
                    $display("[ok] Read 0x%08X from OUTPUT PINS", got);
                    if (state !== 8'hFF && x4_dbg !== {24'h0, state}) begin
                        $display("[tb] FAIL x4 = 0x%08X, expected 0x%02X", x4_dbg, state);
                        errors = errors + 1;
                        aborted = 1;
                    end
                end
            end
        end
    endtask

    task send_byte(input [7:0] b);
        integer k;
        begin
            @(negedge clk); rx = 0;                    // start bit
            repeat (BIT) @(negedge clk);
            for (k = 0; k < 8; k = k + 1) begin        // LSB first
                rx = b[k];
                repeat (BIT) @(negedge clk);
            end
            rx = 1;                                    // stop bit
            repeat (BIT) @(negedge clk);
        end
    endtask

    task emu_t(input integer n, input [31:0] value);
        integer k;
        begin
            if (!aborted) begin
                repeat (`EMU_T_GAP) @(negedge clk);
                for (k = 0; k < n; k = k + 1) begin    // low byte first
                    send_byte(value[8 * k +: 8]);
                    if (k != n - 1) repeat (`EMU_BYTE_GAP) @(negedge clk);
                end
                case (n)
                    1: $display("[ok] Written 0x%02X to UART RX", value[7:0]);
                    2: $display("[ok] Written 0x%04X to UART RX", value[15:0]);
                    default: $display("[ok] Written 0x%08X to UART RX", value);
                endcase
            end
        end
    endtask

    task emu_r(input integer n, input [31:0] value);
        integer waited;
        reg [31:0] got;
        integer k;
        begin
            if (!aborted) begin
                repeat (`EMU_GAP) @(negedge clk);
                if (rx_ptr + n > 8) begin
                    // emu.c's fpga_read_uart returns 1 past the 64-bit window.
                    $display("[error] \"fpga_read_uart\" error: 1");
                    errors = errors + 1;
                    aborted = 1;
                end else begin
                    waited = 0;
                    while (rx_count < rx_ptr + n && waited < 200000) begin
                        @(negedge clk);
                        waited = waited + 1;
                    end
                    if (rx_count < rx_ptr + n) begin
                        $display("[tb] FAIL timeout waiting for %0d reply byte(s), have %0d",
                                 n, rx_count - rx_ptr);
                        errors = errors + 1;
                        aborted = 1;
                    end else begin
                        got = 32'h0;
                        for (k = 0; k < n; k = k + 1)
                            got[8 * k +: 8] = rx_buf[rx_ptr + k];
                        if (got !== value) begin
                            case (n)
                                1: $display("[error] UART read error. Expected 0x%02X. Got 0x%02X",
                                            value[7:0], got[7:0]);
                                2: $display("[error] UART read error. Expected 0x%04X. Got 0x%04X",
                                            value[15:0], got[15:0]);
                                default: $display("[error] UART read error. Expected 0x%08X. Got 0x%08X",
                                                  value, got);
                            endcase
                            errors = errors + 1;
                            aborted = 1;
                        end else begin
                            case (n)
                                1: $display("[ok] Read 0x%02X from UART TX", got[7:0]);
                                2: $display("[ok] Read 0x%04X from UART TX", got[15:0]);
                                default: $display("[ok] Read 0x%08X from UART TX", got);
                            endcase
                        end
                        rx_ptr = rx_ptr + n;
                    end
                end
            end
        end
    endtask

    task emu_end;
        begin
            repeat (`EMU_GAP) @(negedge clk);
            // Only meaningful when the run completed: an aborted run leaves
            // unread bytes by design.
            if (!aborted && rx_count > rx_ptr) begin
                $display("[tb] FAIL unread reply bytes: %0d received, %0d read",
                         rx_count, rx_ptr);
                errors = errors + 1;
            end
            if (halted) begin
                $display("[tb] FAIL halt asserted (ecall/ebreak or illegal instruction)");
                errors = errors + 1;
            end
            if (errors == 0) $display("SCENARIO RESULT: PASS");
            else             $display("SCENARIO RESULT: FAIL (%0d errors)", errors);
            $finish;
        end
    endtask

    initial begin
`ifndef NO_VCD
        $dumpfile("app.vcd");
        $dumpvars(0, testbench);
`endif
`include "scenario.vh"
    end

    initial begin
`ifndef TB_TIMEOUT_NS
`define TB_TIMEOUT_NS 250_000_000
`endif
        #(`TB_TIMEOUT_NS);
        $display("[tb] FAIL timeout");
        $display("SCENARIO RESULT: FAIL (%0d errors)", errors + 1);
        $finish;
    end

endmodule
